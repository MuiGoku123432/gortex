// cobolNameNormRule identifies the versioned label and name matching rule
// cobolNameNorm implements (D-18). Record it wherever a match depends on it.
const cobolNameNormRule = "cobol-name-norm/1"

// cobolWalk indexes one handoff's observations once and carries what every
// breadth walker needs to turn them into nodes and edges.
//
// PURPOSE: one children index, one owning-program pass, and the shared node
// and edge builders, so each walker (procedure, data, refs, mainframe, SQL)
// only decides what to emit.
// RATIONALE: observations carry no field names and the grammar's Parent
// links are flat under start, so roles and ownership come from child kinds,
// span order, and the nearest program_definition ancestor.
// KEYWORDS: cobol, handoff, observations, provenance, prov_*.
type cobolWalk struct {
	h        handoff.Handoff
	src      []byte
	filePath string
	docMeta  map[string]any
	result   *parser.ExtractionResult

	children [][]int        // observation index -> child indexes in span order
	last     []int          // observation index -> last index in its subtree
	owner    []int          // observation index -> owning program_definition, or -1
	programs map[int]string // program_definition index -> program symbol

	// Filled by cobolProcedure for every observation inside a procedure
	// division: the membership container symbol (paragraph, else section,
	// else procedure division) and the flow source symbol (paragraph, else
	// section, else program). Empty outside any procedure division.
	container []string
	flowFrom  []string
}

// newCobolWalk builds the children index, subtree ends, and owning-program
// map for h. Parent links are bounds-checked (never trusted blindly), and
// parsefacts.Validate guarantees Parent < index, so one forward pass sets
// ownership and one reverse pass sets subtree ends.
func newCobolWalk(h handoff.Handoff, src []byte, filePath string, docMeta map[string]any, programs []cobolProgramSymbol, result *parser.ExtractionResult) *cobolWalk {
	obs := h.Facts.Observations
	w := &cobolWalk{
		h: h, src: src, filePath: filePath, docMeta: docMeta, result: result,
		children:  make([][]int, len(obs)),
		last:      make([]int, len(obs)),
		owner:     make([]int, len(obs)),
		programs:  make(map[int]string, len(programs)),
		container: make([]string, len(obs)),
		flowFrom:  make([]string, len(obs)),
	}
	for _, p := range programs {
		w.programs[p.index] = p.symbol
	}
	for i, o := range obs {
		w.last[i] = i
		w.owner[i] = -1
		if o.Kind == "program_definition" {
			w.owner[i] = i
		}
		p, ok := w.parent(i)
		if !ok {
			continue
		}
		w.children[p] = append(w.children[p], i)
		if w.owner[i] < 0 {
			w.owner[i] = w.owner[p]
		}
	}
	for i := len(obs) - 1; i >= 0; i-- {
		if p, ok := w.parent(i); ok && w.last[i] > w.last[p] {
			w.last[p] = w.last[i]
		}
	}
	return w
}

// parent returns observation i's parent index when it is a valid, earlier
// observation.
func (w *cobolWalk) parent(i int) (int, bool) {
	p := w.h.Facts.Observations[i].Parent
	return p, p >= 0 && p < i
}

// text returns the generated bytes of observation i (names come from
// Generated, P2 D-10).
func (w *cobolWalk) text(i int) string {
	g := w.h.Facts.Observations[i].Generated
	return string(w.h.Generated[g.Start:g.End])
}

// programSymbol returns the symbol of the named program that owns
// observation i, or "" when it is outside every program or under an unnamed
// one (the file node already records prov_unnamed_program_count).
func (w *cobolWalk) programSymbol(i int) string {
	if w.owner[i] < 0 {
		return ""
	}
	return w.programs[w.owner[i]]
}

// statementSymbol returns the QualName of the innermost statement node
// among observation i and its Parent ancestors, or "" when there is none.
func (w *cobolWalk) statementSymbol(i int) string { return "" }

// statementNode returns the statement node of observation i, or nil.
func (w *cobolWalk) statementNode(i int) *graph.Node { return nil }

// symbolNode appends a symbol node with ID <filePath>::<symbol>, the cloned
// document provenance, cobol_kind, and the observation kind and Affected
// flag of observation occurrence. The caller stamps its range.
func (w *cobolWalk) symbolNode(symbol, name string, kind graph.NodeKind, cobolKind string, occurrence int) *graph.Node {
	o := w.h.Facts.Observations[occurrence]
	meta := maps.Clone(w.docMeta)
	meta["cobol_kind"] = cobolKind
	meta["prov_observation_kind"] = o.Kind
	meta["prov_affected"] = o.Affected
	node := &graph.Node{
		ID: w.filePath + "::" + symbol, Kind: kind, Name: name, QualName: symbol,
		FilePath: w.filePath, Language: "cobol", Meta: meta,
	}
	w.result.Nodes = append(w.result.Nodes, node)
	return node
}

// defines appends the file-to-symbol structural edge (D-17: no Meta).
func (w *cobolWalk) defines(id string, line int) {
	w.structural(w.filePath, id, graph.EdgeDefines, line)
}

// memberOf appends the child-to-container structural edge (D-17: no Meta).
func (w *cobolWalk) memberOf(child, parent string, line int) {
	w.structural(child, parent, graph.EdgeMemberOf, line)
}

func (w *cobolWalk) structural(from, to string, kind graph.EdgeKind, line int) {
	w.result.Edges = append(w.result.Edges, &graph.Edge{
		From: from, To: to, Kind: kind, FilePath: w.filePath, Line: line,
		Origin: graph.OriginASTResolved, Confidence: 1.0, ConfidenceLabel: "EXTRACTED",
	})
}

// relationEdge appends and returns a relationship edge for the statement
// observation occurrence: the cloned document provenance, the observation
// kind and Affected flag, and the occurrence's original range keys, with
// Line the occurrence's 1-based start line (0 when it has no image). The
// fact is deterministic even when to is an unresolved placeholder.
func (w *cobolWalk) relationEdge(from, to string, kind graph.EdgeKind, occurrence int) *graph.Edge {
	o := w.h.Facts.Observations[occurrence]
	meta := maps.Clone(w.docMeta)
	meta["prov_observation_kind"] = o.Kind
	meta["prov_affected"] = o.Affected
	line := cobolStampMeta(meta, o.Original)
	edge := &graph.Edge{
		From: from, To: to, Kind: kind, FilePath: w.filePath, Line: line,
		Origin: graph.OriginASTResolved, Confidence: 1.0, ConfidenceLabel: "EXTRACTED",
		Meta: meta,
	}
	w.result.Edges = append(w.result.Edges, edge)
	return edge
}

// cobolNameNorm is the cobol-name-norm/1 matching key (D-18): when raw is
// wrapped in one matching pair of quotes (' or "), drop that pair and
// un-double the embedded quote; then upper-fold ASCII letters only, leaving
// every other byte untouched. Node names and IDs keep the source spelling.
func cobolNameNorm(raw string) string {
	if n := len(raw); n >= 2 && (raw[0] == '\'' || raw[0] == '"') && raw[n-1] == raw[0] {
		q := raw[:1]
		raw = strings.ReplaceAll(raw[1:n-1], q+q, q)
	}
	b := []byte(raw)
	for i, c := range b {
		if c >= 'a' && c <= 'z' {
			b[i] = c - ('a' - 'A')
		}
	}
	return string(b)
}

// cobolIDSegment percent-encodes the ID metacharacters %, :, /, # and every
// control byte (below 0x20, or 0x7f) in a name-derived ID segment, so source
// text cannot forge an ::unresolved:: marker, an extra path segment, or a
// #k ordinal (Pitfall 9). Every other byte passes through.
func cobolIDSegment(raw string) string {
	const hex = "0123456789ABCDEF"
	var b strings.Builder
	for i := 0; i < len(raw); i++ {
		c := raw[i]
		if c == '%' || c == ':' || c == '/' || c == '#' || c < 0x20 || c == 0x7f {
			b.WriteByte('%')
			b.WriteByte(hex[c>>4])
			b.WriteByte(hex[c&0x0f])
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

// cobolStampMeta writes the original-coordinate range keys of r into meta
// and returns its 1-based start line. Coordinates are written only when r
// images original bytes; a missing or no-image projection and one made only
// of inserted (synthetic) bytes get prov_range_exact=false and a
// prov_range_absence reason instead, and the return is 0.
func cobolStampMeta(meta map[string]any, r *sourcemap.Projection) int {
	switch {
	case r == nil || r.NoImage:
		meta["prov_range_exact"] = false
		meta["prov_range_absence"] = "no_original_projection"
		return 0
	case r.Synthetic:
		meta["prov_range_exact"] = false
		meta["prov_range_absence"] = "synthetic_projection"
		return 0
	}
	meta["prov_start_row"] = int(r.Start.Row)
	meta["prov_start_column"] = int(r.Start.Column)
	meta["prov_end_row"] = int(r.End.Row)
	meta["prov_end_column"] = int(r.End.Column)
	meta["prov_start_byte"] = int(r.Start.Byte)
	meta["prov_end_byte"] = int(r.End.Byte)
	meta["prov_range_exact"] = r.Exact
	return int(r.Start.Row) + 1
}

// cobolStampExtent stamps a paragraph or procedure section range from its
// header projection start to the end projection of the last observation
// before the header that ends it (Pitfall 1). Both ends must be exact,
// imaged, non-synthetic projections; otherwise only the header range is
// stamped, with prov_range_exact=false and
// prov_range_absence=paragraph_extent_unmapped. A header with no usable
// image behaves exactly like cobolStampRange(node, start).
func cobolStampExtent(node *graph.Node, start, end *sourcemap.Projection) {
	usable := func(r *sourcemap.Projection) bool { return r != nil && !r.NoImage && !r.Synthetic }
	cobolStampRange(node, start)
	if !usable(start) {
		return
	}
	if !start.Exact || !usable(end) || !end.Exact {
		node.Meta["prov_range_exact"] = false
		node.Meta["prov_range_absence"] = "paragraph_extent_unmapped"
		return
	}
	node.EndLine = int(end.End.Row) + 1
	node.EndColumn = int(end.End.Column)
	node.Meta["prov_end_row"] = int(end.End.Row)
	node.Meta["prov_end_column"] = int(end.End.Column)
	node.Meta["prov_end_byte"] = int(end.End.Byte)
}

// cobolDedupeEdges collapses relationship edges (those whose Meta carries
// prov_observation_kind) that share From, To, Kind, and Line, so SQLite
// (first insert wins) and the in-memory graph (last write wins) persist the
// same edge (Pitfall 4). The survivor keeps the first occurrence's Meta and
// gains int cobol_occurrence_count; when the duplicate carries
// cobol_statement_symbol, both symbols are listed in source order in
// cobol_statement_symbols. Structural edges pass through; order is kept.
func cobolDedupeEdges(edges []*graph.Edge) []*graph.Edge {
	first := make(map[string]*graph.Edge)
	out := edges[:0:0]
	for _, e := range edges {
		if _, relation := e.Meta["prov_observation_kind"]; !relation {
			out = append(out, e)
			continue
		}
		key := e.From + "|" + e.To + "|" + string(e.Kind) + "|" + strconv.Itoa(e.Line)
		survivor, dup := first[key]
		if !dup {
			first[key] = e
			out = append(out, e)
			continue
		}
		count, _ := survivor.Meta["cobol_occurrence_count"].(int)
		if count == 0 {
			count = 1
		}
		survivor.Meta["cobol_occurrence_count"] = count + 1
		if sym, ok := e.Meta["cobol_statement_symbol"].(string); ok {
			syms, _ := survivor.Meta["cobol_statement_symbols"].([]string)
			if len(syms) == 0 {
				if own, ok := survivor.Meta["cobol_statement_symbol"].(string); ok {
					syms = append(syms, own)
				}
			}
			survivor.Meta["cobol_statement_symbols"] = append(syms, sym)
		}
	}
	return out
}
